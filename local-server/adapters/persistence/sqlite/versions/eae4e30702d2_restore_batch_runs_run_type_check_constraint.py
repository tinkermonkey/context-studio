"""Restore named run_type CHECK constraint on batch_runs

Revision ID: eae4e30702d2
Revises: 5acc1ebd83f7
Create Date: 2026-10-23 12:00:00.000000

Why this migration exists
-------------------------
The ``BatchRun`` model declares ``CheckConstraint(..., name="check_valid_run_type")``
covering every run type, but databases in the wild disagree with it:

* Fresh databases have no run_type CHECK at all. ``518a8c514f35`` rebuilt
  ``batch_runs`` with an *unnamed* CHECK, and ``f79a82b425a2`` then used
  ``op.batch_alter_table("batch_runs")``. On SQLite that recreates the table from
  reflection, and SQLAlchemy's SQLite reflection drops unnamed CHECK constraints.
* Some long-lived databases still carry the original narrow
  ``CONSTRAINT check_valid_run_type CHECK (run_type IN ('import', 'extraction'))``,
  which rejects ``individual_extraction``/``schema_extraction`` runs.

Why this is not autogenerated
-----------------------------
Alembic autogenerate does not compare CHECK constraints, so it cannot detect
either discrepancy (``alembic check`` only reports column-type drift on this
table). Batch mode (``batch_alter_table``) is also unsuitable: it rebuilds from
reflection, which is exactly what lost the constraint, and it would carry over
each database's divergent column types. This migration therefore rebuilds the
table explicitly, mirroring ``518a8c514f35``, to one fixed target DDL that
matches the model (column types, named CHECK, ``batch_id`` FK and all indexes).
The rebuild is unconditional, so it is idempotent: it produces the same table
whether the starting state has the narrow constraint, no constraint, or the
correct one. Rows are copied with an explicit column list (column order differs
between databases). Rows whose run_type would violate the CHECK make the
upgrade fail loudly rather than being dropped.

The rebuild requires ``PRAGMA foreign_keys`` to be OFF (the Alembic connection
never enables it); with it ON, ``DROP TABLE`` would cascade-delete child rows in
change_events/import_runs/extraction_runs/pipeline_runs.

Downgrade
---------
Rebuilds the table the same way but without the run_type CHECK, i.e. the state
a fresh database had at ``5acc1ebd83f7``. It does not restore the narrow named
constraint that some long-lived databases had before this upgrade.
"""

