def _require_foreign_keys_off() -> None:
    """Refuse to rebuild ontology_entities while SQLite enforces foreign keys."""
    if op.get_bind().exec_driver_sql("PRAGMA foreign_keys").scalar():
        raise RuntimeError("PRAGMA foreign_keys must be OFF to rebuild ontology_entities")


def _json_list(value: Any) -> list[dict[str, Any]]:
    """A stored JSON list column as a Python list (tolerates raw strings and NULL)."""
    if isinstance(value, str):
        value = json.loads(value)
    return list(value or [])


def _dr_spec_reference(refs: list[dict[str, Any]]) -> dict[str, Any] | None:
    """The documentation_robotics/spec reference among a taxonomy's references."""
    for ref in refs:
        if ref.get("source") == DR_SOURCE and ref.get("identifier") == DR_SPEC_IDENTIFIER:
            return ref
    return None


_INVALID_PREDICATE_CHARS = re.compile(r"[^a-z0-9_-]+")


def _predicate_identifier(value: str) -> str:
    """A valid predicate identifier (^[a-z][a-z0-9_-]{0,254}$) made from value."""
    cleaned = _INVALID_PREDICATE_CHARS.sub("_", value.strip().lower()).strip("_-")
    if not cleaned or not cleaned[0].isalpha():
        cleaned = f"p_{cleaned}"
    return cleaned[:255]


def _insert_predicate(
    conn: Any,
    taxonomy_id: str,
    identifier: str,
    description: str | None = None,
    external_references: list[dict[str, Any]] | None = None,
) -> str:
    """Insert a draft predicate and return its id."""
    now = datetime.now(timezone.utc)
    predicate_id = str(uuid.uuid4())
    conn.execute(
        predicates_table.insert().values(
            id=predicate_id,
            taxonomy_id=taxonomy_id,
            identifier=identifier,
            title=identifier,
            description=description,
            external_references=external_references or [],
            status="draft",
            version=1,
            created_at=now,
            last_modified=now,
        )
    )
    return predicate_id


def _move_dr_catalogs(conn: Any) -> dict[tuple[str, str], str]:
    """Step a: DR taxonomy catalogs into predicate rows. Returns (taxonomy, identifier) -> id."""
    created: dict[tuple[str, str], str] = {}
    taxonomies = conn.execute(
        sa.text(
            "SELECT id, external_references FROM ontology_entities WHERE node_type = 'taxonomy'"
        )
    ).fetchall()
    for taxonomy_id, raw_refs in taxonomies:
        refs = _json_list(raw_refs)
        spec = _dr_spec_reference(refs)
        metadata = (spec or {}).get("metadata") or {}
        catalog = metadata.get("predicates")
        if not isinstance(catalog, dict):
            continue
        for raw_identifier, entry in catalog.items():
            identifier = _predicate_identifier(raw_identifier)
            entry = entry if isinstance(entry, dict) else {}
            dr_metadata = {k: entry[k] for k in DR_PREDICATE_METADATA if k in entry}
            created[(taxonomy_id, identifier)] = _insert_predicate(
                conn,
                taxonomy_id,
                identifier,
                description=entry.get("description"),
                external_references=[
                    {
                        "source": DR_SOURCE,
                        "identifier": identifier,
                        "uri": None,
                        "metadata": dr_metadata,
                    }
                ],
            )
        spec["metadata"] = {k: v for k, v in metadata.items() if k != "predicates"}  # type: ignore[index]
        conn.execute(
            entities_table.update()
            .where(entities_table.c.id == taxonomy_id)
            .values(external_references=refs)
        )
    return created


def _relationship_source_taxonomies(conn: Any) -> dict[str, str]:
    """Per relationship type, the taxonomy its relationships' sources most often belong to."""
    rows = conn.execute(
        sa.text(
            "SELECT r.property_definition_id, s.taxonomy_id, COUNT(*)"
            " FROM relationships r JOIN ontology_entities s ON s.id = r.source_id"
            " WHERE s.taxonomy_id IS NOT NULL"
            " GROUP BY r.property_definition_id, s.taxonomy_id"
        )
    ).fetchall()
    counts: dict[str, Counter[str]] = {}
    for type_id, taxonomy_id, count in rows:
        counts.setdefault(type_id, Counter())[taxonomy_id] = count
    return {
        type_id: min(c, key=lambda t: (-c[t], t))  # most edges, then lowest id
        for type_id, c in counts.items()
    }


def _link_relationship_types(conn: Any, catalog: dict[tuple[str, str], str]) -> None:
    """Step b: point every relationship type at a predicate in its taxonomy."""
    by_edges = _relationship_source_taxonomies(conn)
    types = conn.execute(
        sa.text(
            "SELECT pd.id, pd.identifier, pd.canonical_predicate,"
            " dc.taxonomy_id, rc.taxonomy_id"
            " FROM ontology_entities pd"
            " LEFT JOIN ontology_entities dc ON dc.id = pd.domain_class_id"
            " LEFT JOIN ontology_entities rc ON rc.id = pd.range_class_id"
            " WHERE pd.node_type = 'property_definition'"
        )
    ).fetchall()
    for type_id, identifier, canonical, domain_taxonomy, range_taxonomy in types:
        taxonomy_id = domain_taxonomy or range_taxonomy or by_edges.get(type_id)
        if taxonomy_id is None:
            print(f"Relationship type {identifier!r} has no taxonomy; left without a predicate")
            continue
        raw = canonical or identifier
        predicate = _predicate_identifier(raw)
        if predicate != raw:
            print(f"Relationship type {identifier!r}: predicate {raw!r} becomes {predicate!r}")
        key = (taxonomy_id, predicate)
        if key not in catalog:
            catalog[key] = _insert_predicate(conn, taxonomy_id, predicate)
        conn.execute(
            entities_table.update()
            .where(entities_table.c.id == type_id)
            .values(predicate_id=catalog[key])
        )


