def _restore_dr_catalogs(conn: Any) -> None:
    """Best effort: put DR predicates back on their taxonomy's spec reference metadata."""
    taxonomies = conn.execute(
        sa.text(
            "SELECT id, external_references FROM ontology_entities WHERE node_type = 'taxonomy'"
        )
    ).fetchall()
    for taxonomy_id, raw_refs in taxonomies:
        refs = _json_list(raw_refs)
        spec = _dr_spec_reference(refs)
        if spec is None:
            continue
        catalog: dict[str, dict[str, Any]] = {}
        rows = conn.execute(
            sa.text(
                "SELECT identifier, description, external_references FROM predicates"
                " WHERE taxonomy_id = :taxonomy_id ORDER BY identifier"
            ),
            {"taxonomy_id": taxonomy_id},
        ).fetchall()
        for identifier, description, raw_predicate_refs in rows:
            dr_ref = next(
                (r for r in _json_list(raw_predicate_refs) if r.get("source") == DR_SOURCE), None
            )
            if dr_ref is None:
                continue
            entry = dict(dr_ref.get("metadata") or {})
            entry["description"] = description
            catalog[identifier] = entry
        spec["metadata"] = {**(spec.get("metadata") or {}), "predicates": catalog}
        conn.execute(
            entities_table.update()
            .where(entities_table.c.id == taxonomy_id)
            .values(external_references=refs)
        )


