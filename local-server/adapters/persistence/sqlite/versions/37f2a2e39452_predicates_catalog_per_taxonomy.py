DR_SOURCE = "documentation_robotics"
DR_SPEC_IDENTIFIER = "spec"
# Catalog entry fields that ride on a predicate's DR reference metadata
DR_PREDICATE_METADATA = ("inverse", "category", "archimate_alignment", "semantics")

