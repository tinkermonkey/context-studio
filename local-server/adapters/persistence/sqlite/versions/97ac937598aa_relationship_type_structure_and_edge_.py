def _edge_attribute_names(conn: Any) -> dict[str, list[str]]:
    """Per relationship type, its edge attribute identifiers in order."""
    rows = conn.execute(
        sa.text(
            "SELECT property_definition_id, identifier FROM attribute_definitions"
            " WHERE property_definition_id IS NOT NULL"
            " ORDER BY property_definition_id, sort_order, identifier"
        )
    ).fetchall()
    names: dict[str, list[str]] = {}
    for type_id, name in rows:
        names.setdefault(type_id, []).append(name)
    return names


def _restore_metadata(conn: Any) -> None:
    """Best effort: put the structure back into reference metadata."""
    edge_names = _edge_attribute_names(conn)
    rows = conn.execute(
        sa.text(
            "SELECT id, identifier, external_references, min_per_source, max_per_source,"
            " max_per_target, hierarchy, symmetric FROM ontology_entities"
            " WHERE node_type = 'property_definition' ORDER BY id"
        )
    ).fetchall()
    for type_id, identifier, raw_refs, min_s, max_s, max_t, hierarchy, symmetric in rows:
        refs = _json_list(raw_refs)
        house = next((r for r in refs if r.get("source") == HOUSE_SOURCE), None)
        dr = next((r for r in refs if r.get("source") == DR_SOURCE), None)
        if house is not None:
            metadata = dict(house.get("metadata") or {})
            metadata.update(
                min=min_s, max=max_s, hierarchy=bool(hierarchy), symmetric=bool(symmetric)
            )
            if type_id in edge_names:
                kept = metadata.get("edge_properties") or []
                metadata["edge_properties"] = edge_names[type_id] + list(kept)
            house["metadata"] = metadata
        if dr is not None:
            metadata = dict(dr.get("metadata") or {})
            cardinality = DR_CARDINALITY_BY_NUMBERS.get((max_s, max_t))
            if "cardinality" in metadata:
                pass  # an unknown value the upgrade left in place
            elif cardinality is None:
                print(
                    f"Relationship type {identifier!r}: ({max_s}, {max_t}) isn't a DR cardinality"
                )
            else:
                metadata["cardinality"] = cardinality
            dr["metadata"] = metadata
        if house is None and dr is None and type_id in edge_names:
            print(f"Relationship type {identifier!r}: edge attributes dropped with no reference")
        if house is not None or dr is not None:
            conn.execute(
                entities_table.update()
                .where(entities_table.c.id == type_id)
                .values(external_references=refs)
            )
    conn.execute(
        sa.text("DELETE FROM attribute_definitions WHERE property_definition_id IS NOT NULL")
    )


