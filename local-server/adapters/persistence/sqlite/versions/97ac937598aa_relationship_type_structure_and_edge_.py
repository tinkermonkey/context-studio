def _require_foreign_keys_off() -> None:
    """Refuse to rebuild tables while SQLite enforces foreign keys."""
    if op.get_bind().exec_driver_sql("PRAGMA foreign_keys").scalar():
        raise RuntimeError("PRAGMA foreign_keys must be OFF to rebuild ontology tables")


def _json_list(value: Any) -> list[dict[str, Any]]:
    """A stored JSON list column as a Python list (tolerates raw strings and NULL)."""
    if isinstance(value, str):
        value = json.loads(value)
    return list(value or [])


def _whole_number(value: Any) -> int | None:
    """value as an int (None for a non-number, a bool, or None)."""
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, float) and value.is_integer():
        return int(value)
    if isinstance(value, str) and value.strip().isdigit():
        return int(value.strip())
    return None


def _relationship_types(conn: Any) -> list[tuple[str, str, list[dict[str, Any]]]]:
    """Every relationship type as (id, identifier, external references)."""
    rows = conn.execute(
        sa.text(
            "SELECT id, identifier, external_references FROM ontology_entities"
            " WHERE node_type = 'property_definition' ORDER BY id"
        )
    ).fetchall()
    return [(type_id, identifier, _json_list(refs)) for type_id, identifier, refs in rows]


def _insert_edge_attributes(conn: Any, type_id: str, names: list[str]) -> None:
    """One draft edge attribute per name, owned by the relationship type."""
    now = datetime.now(timezone.utc)
    for sort_order, name in enumerate(names):
        datatype, allowed_values = EDGE_ATTRIBUTE_TYPES.get(name, ("string", None))
        conn.execute(
            attributes_table.insert().values(
                id=str(uuid.uuid4()),
                class_id=None,
                property_definition_id=type_id,
                identifier=name,
                title=name,
                datatype=datatype,
                is_required=False,
                allowed_values=allowed_values,
                sort_order=sort_order,
                external_references=[],
                status="draft",
                version=1,
                created_at=now,
                last_modified=now,
            )
        )


def _lift_structure(conn: Any) -> None:
    """Steps a and b: reference metadata into the structure columns and edge attributes."""
    for type_id, identifier, refs in _relationship_types(conn):
        values: dict[str, Any] = {}
        edge_names: list[str] = []
        for ref in refs:
            metadata = dict(ref.get("metadata") or {})
            lifted = False
            if any(key in metadata for key in STRUCTURE_KEYS):
                lifted = True
                values["min_per_source"] = _whole_number(metadata.pop("min", None)) or 0
                values["max_per_source"] = _whole_number(metadata.pop("max", None))
                values["hierarchy"] = bool(metadata.pop("hierarchy", False))
                values["symmetric"] = bool(metadata.pop("symmetric", False))
                invalid: list[Any] = []
                for name in metadata.pop("edge_properties", None) or []:
                    if isinstance(name, str) and _IDENTIFIER.match(name):
                        if name not in edge_names:
                            edge_names.append(name)
                    else:
                        invalid.append(name)
                if invalid:
                    print(
                        f"Relationship type {identifier!r}: edge properties {invalid!r}"
                        " aren't attribute identifiers; left in its metadata"
                    )
                    metadata["edge_properties"] = invalid
            if ref.get("source") == DR_SOURCE and "cardinality" in metadata:
                cardinality = metadata["cardinality"]
                if cardinality in DR_CARDINALITY:
                    lifted = True
                    del metadata["cardinality"]
                    max_source, max_target = DR_CARDINALITY[cardinality]
                    values["max_per_source"] = max_source
                    values["max_per_target"] = max_target
                else:
                    print(
                        f"Relationship type {identifier!r}: unknown DR cardinality"
                        f" {cardinality!r}; left in its metadata"
                    )
            if lifted:
                # None when nothing is left, as the mappers and bundle planner write it
                ref["metadata"] = metadata or None
        if not values and not edge_names:
            continue
        conn.execute(
            entities_table.update()
            .where(entities_table.c.id == type_id)
            .values(external_references=refs, **values)
        )
        _insert_edge_attributes(conn, type_id, edge_names)


